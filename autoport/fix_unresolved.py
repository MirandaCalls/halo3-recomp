#!/usr/bin/env python3
"""Iteratively run `rexglue codegen` and auto-resolve tail-merged branch targets.

MSVC/XDK code often shares epilogues between functions: function A does a plain
`b X` into the tail of function B. ReXGlue reports this as
`UnresolvedCall ... target not in any function`. We fix it by declaring the
range [X, end_of_B) as a discontinuous chunk of A in a per-module include file.
"""

import argparse
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

RE_FAILED = re.compile(r"Analysis failed for '([^']+)'")
RE_UNRESOLVED = re.compile(r"^\s+0x([0-9A-F]+) from 0x([0-9A-F]+): b ", re.M)
RE_JUMP_OWNER = re.compile(r"added unresolved jump 0x([0-9A-F]+)->0x([0-9A-F]+) to function 0x([0-9A-F]+)")
RE_GAPFILL = re.compile(r"GapFill: registered \S+ \(0x([0-9A-F]+)-0x([0-9A-F]+)")
RE_DISCOVERED = re.compile(r"FunctionNode 0x([0-9A-F]+) \(\w+\): DISCOVERED with \d+ blocks, (\d+) instructions")
RE_PDATA_SIZED = re.compile(r"discoverBlocks: entry=0x([0-9A-F]+) pdataSize=(\d+) funcEnd=0x([0-9A-F]+)")
RE_PDATA = re.compile(r"discoverBlocks: entry=0x([0-9A-F]+) pdataSize=\d+ funcEnd=0x([0-9A-F]+)")


def run_codegen(rexglue, manifest, log_path):
    with open(log_path, "w") as f:
        # Defaults that every game needs (e.g. Blam! script dispatch has >1000 cases).
        extra = os.environ.get("AUTOPORT_REXGLUE_ARGS", "--max_jump_table_entries=4096").split()
        proc = subprocess.run([rexglue, "-v", *extra, "codegen", manifest.name, "--ignore-stamp"],
                              cwd=manifest.parent, stdout=f, stderr=subprocess.STDOUT)
    return proc.returncode, log_path.read_text(errors="replace")


def orphan_function_start(manifest, module_name, addr):
    """Walk back from addr to the nearest unconditional terminator; the next word starts the function."""
    import struct
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import xex_image
    data = tomllib.loads(manifest.read_text())
    for b in [data["entrypoint"]] + data.get("modules", []):
        if Path(b["file_path"]).stem.lower() == module_name.lower():
            load, img = xex_image.load(manifest.parent / b["file_path"])
            break
    a = addr - 4
    while a > addr - 0x10000:
        w = struct.unpack(">I", img[a - load:a - load + 4])[0]
        if w in (0x4E800020, 0x4E800420) or ((w >> 26) == 18 and (w & 3) == 0):
            return a + 4
        a -= 4
    return addr


def module_include(manifest, module_name, suffix="auto"):
    """Return the auto include path for a module, adding it to the manifest if needed."""
    text = manifest.read_text()
    data = tomllib.loads(text)
    binaries = [("entrypoint", data["entrypoint"])] + [("modules", m) for m in data.get("modules", [])]
    for _, b in binaries:
        stem = Path(b["file_path"]).stem
        if stem.lower() != module_name.lower():
            continue
        inc = f"config/{stem.lower()}_{suffix}.toml"
        if inc not in b.get("includes", []):
            # Rewrite the includes line that follows this binary's file_path.
            pat = re.compile(r'(file_path = "' + re.escape(b["file_path"]) + r'"\n(?:.*\n)*?includes = \[)([^\]]*)\]')
            def repl(m):
                existing = m.group(2).strip()
                items = (existing + ", " if existing else "") + f'"{inc}"'
                return f"{m.group(1)}{items}]"
            text = pat.sub(repl, text, count=1)
            manifest.write_text(text)
        path = manifest.parent / inc
        if not path.exists():
            path.parent.mkdir(exist_ok=True)
            path.write_text("# Auto-generated by autoport\n\n[functions]\n" if suffix == "auto" else "")
        return path
    raise SystemExit(f"module {module_name} not found in manifest")


RE_FLAGGED = re.compile(r"// FATAL: unresolved function 0x([0-9A-F]+)")


def harvest_flagged_targets(manifest):
    """Codegen succeeds but emits `// FATAL: unresolved function X` for branch targets
    that land outside any function (e.g. code after a no-return call like KeBugCheck).
    Register each X as a function of its module."""
    data = tomllib.loads(manifest.read_text())
    added = 0
    for b in [data["entrypoint"]] + data.get("modules", []):
        out = manifest.parent / b["out_directory_path"]
        targets = set()
        for cpp in out.glob("*_recomp.*.cpp"):
            targets |= {int(x, 16) for x in RE_FLAGGED.findall(cpp.read_text(errors="replace"))}
        if not targets:
            continue
        inc = module_include(manifest, Path(b["file_path"]).stem)
        text = inc.read_text() if inc.exists() else "# Auto-generated by autoport\n\n[functions]\n"
        new = [t for t in sorted(targets) if f"0x{t:08X} = " not in text]
        if new:
            inc.write_text(text + "".join(f"0x{t:08X} = {{}}  # codegen-flagged unresolved target\n" for t in new))
            added += len(new)
    return added


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest", type=Path)
    ap.add_argument("--rexglue", default="rexglue")
    ap.add_argument("--max-iter", type=int, default=20)
    args = ap.parse_args()
    manifest = args.manifest.resolve()
    log_path = manifest.parent / "codegen_auto.log"
    # Recover from interrupted runs: every include the manifest names must exist.
    data = tomllib.loads(manifest.read_text())
    for b in [data["entrypoint"]] + data.get("modules", []):
        for inc in b.get("includes", []):
            p = manifest.parent / inc
            if not p.exists():
                p.parent.mkdir(exist_ok=True)
                p.write_text("# Auto-generated by autoport\n\n[functions]\n" if inc.endswith("_auto.toml") else "")

    for it in range(args.max_iter):
        rc, log = run_codegen(args.rexglue, manifest, log_path)
        if rc == 0:
            added = harvest_flagged_targets(manifest)
            if not added:
                print(f"[iter {it}] codegen OK")
                return 0
            print(f"[iter {it}] codegen OK, {added} flagged unresolved targets registered; regenerating")
            continue
        failed = RE_FAILED.findall(log)
        errors = RE_UNRESOLVED.findall(log)
        if not failed or not errors:
            print(f"[iter {it}] codegen failed with non-fixable errors; see {log_path}")
            return 1
        module = failed[-1]
        # Only use trace lines from the failing module's analysis (last section).
        start = log.rfind("start  ", 0, log.rfind(f"phase  {module}")) if f"phase  {module}" in log else 0
        section = log[max(start, 0):]

        owners = {(int(src, 16), int(dst, 16)): int(fn, 16) for src, dst, fn in RE_JUMP_OWNER.findall(section)}
        ranges = [(int(a, 16), int(b, 16)) for a, b in RE_GAPFILL.findall(section)]
        ranges += [(int(a, 16), int(b, 16)) for a, b in RE_PDATA.findall(section)]

        inc = module_include(manifest, module)
        inc.parent.mkdir(exist_ok=True)
        pdata_funcs = [(int(a, 16), int(b, 16)) for a, n, b in RE_PDATA_SIZED.findall(section) if int(n)]
        # Real size of each discovered function (GapFill segments can overlap the next function).
        gap_sizes = {int(a, 16): int(n) * 4 for a, n in RE_DISCOVERED.findall(section)}
        lines = []
        for dst_s, src_s in errors:
            dst, src = int(dst_s, 16), int(src_s, 16)
            owner = owners.get((src, dst))
            if owner is None:
                print(f"  cannot auto-fix b 0x{dst:08X} from 0x{src:08X}")
                return 1
            if gap_sizes.get(owner, 1 << 30) <= 16:
                # Cold block: the compiler outlined a rarely-taken path of some
                # function after its blr; the "stub" jumps back into that function.
                # Make the stub a chunk of the function that contains the target.
                parent = next((a for a, b in pdata_funcs if a <= dst < b), None)
                if parent is None:
                    parent = orphan_function_start(manifest, module, dst)
                    lines.append(f"0x{parent:08X} = {{}}  # orphan function containing cold-block target")
                lines.append(f"0x{owner:08X} = {{ parent = 0x{parent:08X}, size = {gap_sizes[owner]} }}"
                             f"  # cold block: b 0x{dst:08X} from 0x{src:08X}")
                continue
            containing = [e for s, e in ranges if s < dst < e]
            if not containing:
                print(f"  cannot auto-fix b 0x{dst:08X} from 0x{src:08X}")
                return 1
            end = min(containing)
            lines.append(f"0x{dst:08X} = {{ parent = 0x{owner:08X}, size = {end - dst} }}"
                         f"  # tail-merged: b from 0x{src:08X}")
        existing = inc.read_text() if inc.exists() else "# Auto-generated by autoport/fix_unresolved.py\n\n[functions]\n"
        inc.write_text(existing + "\n".join(lines) + "\n")
        print(f"[iter {it}] {module}: added {len(lines)} chunk overrides -> {inc.relative_to(manifest.parent)}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
