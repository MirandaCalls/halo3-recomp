#!/usr/bin/env python3
"""Generate bodies for guest-DLL -> guest-DLL imports that ReXGlue leaves undefined.

ReXGlue's codegen only resolves kernel (xboxkrnl/xam) import ordinals. An import
from another recompiled guest DLL is declared as `sub_<thunk>` but never defined,
so the module's shared library fails to dlopen. We emit a body per thunk that
resolves the export by ordinal on first call and dispatches through the
recompiled function table.

Input: a `rexglue -v codegen` log. Output: one .cpp per module plus a CMake
snippet that attaches each .cpp to its module target.
"""

import argparse
import re
import tomllib
from collections import defaultdict
from pathlib import Path

RE_PAIR = re.compile(
    r"Cannot resolve ordinal (\d+) from (\S+)\n(?:.*\n){0,3}?.*added import function 0x([0-9A-F]+) -> (sub_[0-9A-F]+)")
RE_BASE = re.compile(r"#define REX_IMAGE_BASE (0x[0-9A-Fa-f]+)")
RE_SIZE = re.compile(r"#define REX_IMAGE_SIZE (0x[0-9A-Fa-f]+)")

TEMPLATE_HEAD = """// Auto-generated by autoport/gen_xdll_imports.py - DO NOT EDIT
// Runtime-resolved imports from other recompiled guest DLLs.

#include "{project}_funcs.h"

#include <rex/system/kernel_state.h>
#include <rex/system/xmodule.h>
#include <rex/logging/macros.h>

namespace {{
PPCFunc* ResolveGuestImport(const char* module, uint16_t ordinal) {{
  auto mod = rex::system::kernel_state()->GetModule(module);
  if (!mod) {{
    REXSYS_ERROR("autoport: import module '{{}}' not loaded (ordinal {{}})", module, ordinal);
    return nullptr;
  }}
  uint32_t addr = mod->GetProcAddressByOrdinal(ordinal);
  if (!addr) {{
    REXSYS_ERROR("autoport: '{{}}' has no export ordinal {{}}", module, ordinal);
    return nullptr;
  }}
  return rex::runtime::ResolveIndirectFunction(addr);
}}
}}  // namespace
"""

TEMPLATE_FUNC = """
DEFINE_REX_FUNC({sym}) {{
  static PPCFunc* target = ResolveGuestImport("{lib}", {ordinal});
  target(ctx, base);
}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest", type=Path)
    ap.add_argument("--log", type=Path, required=True)
    args = ap.parse_args()
    root = args.manifest.resolve().parent
    project = tomllib.loads(args.manifest.read_text())["project"]["name"]
    data = tomllib.loads(args.manifest.read_text())

    # Module image ranges from each generated pch.
    modules = []
    for m in data.get("modules", []):
        out = root / m["out_directory_path"]
        pch = (out / f"{project}_pch.h").read_text()
        base = int(RE_BASE.search(pch).group(1), 16)
        size = int(RE_SIZE.search(pch).group(1), 16)
        target = f"{project}_{Path(m['file_path']).stem}"
        modules.append((base, base + size, out, target))

    per_module = defaultdict(list)
    for ordinal, lib, addr, sym in RE_PAIR.findall(args.log.read_text(errors="replace")):
        a = int(addr, 16)
        for lo, hi, out, target in modules:
            if lo <= a < hi:
                per_module[(out, target)].append((sym, lib, int(ordinal)))
                break

    outdir = root / "src" / "autoport"
    outdir.mkdir(parents=True, exist_ok=True)
    cmake = ["# Auto-generated by autoport/gen_xdll_imports.py - DO NOT EDIT"]
    for (out, target), entries in sorted(per_module.items()):
        seen = {}
        for sym, lib, ordinal in entries:
            seen[sym] = (lib, ordinal)
        src = outdir / f"{target}_xdll_imports.cpp"
        body = TEMPLATE_HEAD.format(project=project) + "".join(
            TEMPLATE_FUNC.format(sym=s, lib=l, ordinal=o) for s, (l, o) in sorted(seen.items()))
        src.write_text(body)
        rel = src.relative_to(root)
        cmake.append(f"if(TARGET {target})\n  target_sources({target} PRIVATE ${{CMAKE_CURRENT_SOURCE_DIR}}/{rel})\nendif()")
        print(f"{target}: {len(seen)} cross-DLL imports -> {rel}")
    (root / "generated" / "autoport_xdll.cmake").write_text("\n".join(cmake) + "\n")


if __name__ == "__main__":
    main()
