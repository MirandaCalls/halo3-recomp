#!/usr/bin/env python3
"""Find MSVC vcall thunks swallowed into neighbouring functions.

MSVC emits pointer-to-virtual-member thunks (`??_9`) as

    lwz r11,0(r3) ; lwz r10,N(r11) ; mtctr r10 ; bctr

They have no .pdata entry and are only reached through data pointers, so
ReXGlue's GapFill often merges them into an adjacent segment. We walk the
generated C++ (one `// <insn>` comment per guest instruction, `loc_X:` labels
as address anchors), find every thunk that does not start its own function,
and emit `0xADDR = {}` into the module's config/<stem>_auto.toml.
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

RE_FUNC = re.compile(r"^DEFINE_REX_FUNC\(sub_([0-9A-F]+)\)")
RE_LABEL = re.compile(r"^loc_([0-9A-F]+):")
RE_INSN = re.compile(r"^\t// (.*?)\s*$")
RE_TERM = re.compile(r"^(blr|bctr|b 0x[0-9A-F]+)$")
THUNK = [re.compile(p) for p in (r"lwz r11,0\(r3\)$", r"lwz r10,\d+\(r11\)$", r"mtctr r10$", r"bctr$")]


def scan_module(out_dir):
    found = []
    for cpp in sorted(out_dir.glob("*_recomp.*.cpp")):
        func = addr = None
        window = []
        for line in cpp.read_text(errors="replace").splitlines():
            if m := RE_FUNC.match(line):
                func = addr = int(m.group(1), 16)
                window = []
            elif m := RE_LABEL.match(line):
                addr = int(m.group(1), 16)
            elif addr is not None and (m := RE_INSN.match(line)):
                window = (window + [(addr, m.group(1))])[-5:]
                addr += 4
                if len(window) == 5 and all(p.match(t) for p, (_, t) in zip(THUNK, window[1:])):
                    start = window[1][0]
                    # Only split when the thunk cannot be reached by fallthrough.
                    if start != func and RE_TERM.match(window[0][1]):
                        found.append(start)
    return sorted(set(found))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest", type=Path)
    args = ap.parse_args()
    manifest = args.manifest.resolve()
    root = manifest.parent
    data = tomllib.loads(manifest.read_text())
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from fix_unresolved import module_include

    total = 0
    for b in [data["entrypoint"]] + data.get("modules", []):
        stem = Path(b["file_path"]).stem
        thunks = scan_module(root / b["out_directory_path"])
        if not thunks:
            continue
        inc = module_include(manifest, stem)
        text = inc.read_text() if inc.exists() else "# Auto-generated by autoport\n\n[functions]\n"
        new = [a for a in thunks if f"0x{a:08X} = " not in text]
        if new:
            text += "".join(f"0x{a:08X} = {{}}  # vcall thunk\n" for a in new)
            inc.write_text(text)
        total += len(new)
        print(f"{stem}: {len(thunks)} embedded vcall thunks, {len(new)} new")
    print(f"total new: {total}")


if __name__ == "__main__":
    main()
