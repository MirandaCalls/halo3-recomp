#!/usr/bin/env python3
"""Generate a kernel-import call tracer for differential debugging against Xenia.

For every `__imp__<Export>` the entrypoint uses, emit a strong override that
(when AUTOPORT_TRACE_IMPORTS=<file> is set) logs
    <guest thread id> <Export>(r3, r4, ..., r10) -> r3
in the same shape as Xenia's debug log, then forwards to the SDK's
implementation found with dlsym(RTLD_NEXT). Diffing the two logs shows the first
kernel call where the recompiled game and Xenia's JIT diverge.
"""

import argparse
import re
import tomllib
from pathlib import Path

# Too frequent to be useful in a trace.
SKIP = {
    "RtlEnterCriticalSection", "RtlLeaveCriticalSection", "RtlTryEnterCriticalSection",
    "KeQueryPerformanceFrequency", "KeQueryPerformanceCounter", "KeTlsGetValue", "KeTlsSetValue",
    "KeGetCurrentProcessType", "KfAcquireSpinLock", "KfReleaseSpinLock", "KeRaiseIrqlToDpcLevel",
    "KfLowerIrql", "KeAcquireSpinLockAtRaisedIrql", "KeReleaseSpinLockFromRaisedIrql",
    "RtlInitAnsiString", "KeQuerySystemTime", "XAudioSubmitRenderDriverFrame",
}

HEADER = """// Auto-generated by autoport/gen_import_tracer.py - DO NOT EDIT
#include <rex/hook.h>
#include <rex/system/kernel_state.h>
#include <rex/system/xthread.h>

#include <dlfcn.h>
#include <cstdio>
#include <cstdlib>
#include <mutex>

namespace {
using ImportFn = void (*)(PPCContext&, uint8_t*);

FILE* TraceFile() {
  static FILE* f = [] {
    const char* p = std::getenv("AUTOPORT_TRACE_IMPORTS");
    return p ? std::fopen(p, "w") : nullptr;
  }();
  return f;
}

std::mutex g_trace_mutex;

uint32_t GuestThreadId() {
  auto* t = rex::system::XThread::GetCurrentThread();
  return t ? t->handle() : 0;
}

void Trace(const char* name, const PPCContext& in, uint64_t ret) {
  FILE* f = TraceFile();
  if (!f) return;
  std::lock_guard lock(g_trace_mutex);
  std::fprintf(f, "%08X %s(%08X, %08X, %08X, %08X, %08X, %08X, %08X, %08X) -> %08X\\n", GuestThreadId(),
               name, in.r3.u32, in.r4.u32, in.r5.u32, in.r6.u32, in.r7.u32, in.r8.u32, in.r9.u32,
               in.r10.u32, uint32_t(ret));
  std::fflush(f);
}
}  // namespace
"""

FUNC = """
REX_HOOK_RAW(__imp__{name}) {{
  static auto real = reinterpret_cast<ImportFn>(dlsym(RTLD_NEXT, "__imp__{name}"));
  if (!TraceFile()) {{
    real(ctx, base);
    return;
  }}
  const PPCContext in = ctx;
  real(ctx, base);
  Trace("{name}", in, ctx.r3.u64);
}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest", type=Path)
    args = ap.parse_args()
    manifest = args.manifest.resolve()
    root = manifest.parent
    data = tomllib.loads(manifest.read_text())
    project = data["project"]["name"]
    gen = root / data["entrypoint"]["out_directory_path"]
    # Imports already overridden by autoport/runtime would collide (and RTLD_NEXT
    # would bypass the override), so leave them untraced.
    overridden = set()
    for src in (Path(__file__).resolve().parent / "runtime").glob("*.cpp"):
        overridden |= set(re.findall(r"REX_HOOK_RAW\(__imp__(\w+)\)", src.read_text()))
    names = sorted(set(re.findall(r"DECLARE_REX_FUNC\(__imp__(\w+)\)",
                                  (gen / f"{project}_funcs.h").read_text())) - SKIP - overridden)
    out = root / "src" / "autoport" / "import_tracer.cpp"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(HEADER + "".join(FUNC.format(name=n) for n in names))
    print(f"{len(names)} imports traced -> {out.relative_to(root)}")


if __name__ == "__main__":
    main()
