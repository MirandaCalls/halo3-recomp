#!/usr/bin/env python3
"""Generate a runtime call tracer for a title's statically linked D3D library.

Engine code reaches much of Xbox D3D through function pointers (the device's
render-state table, draw entry points called with bctrl), which static call
graphs miss. For every recompiled function inside the D3D core range (from
autoport/gpu/triage.py --json) this emits a strong override of the weak
`sub_XXXXXXXX` symbol that counts (caller return address, function) pairs and
forwards to `__imp__sub_XXXXXXXX`. Only calls coming from outside the core are
recorded, so the output is the engine -> D3D boundary.

Enable at runtime with AUTOPORT_D3D_TRACE=<file>; the table is rewritten every
two seconds as "<func> <caller_lr> <count>" lines.
"""
import argparse
import json
import re
import tomllib
from pathlib import Path

HEADER = """// Auto-generated by autoport/gpu/gen_d3d_tracer.py - DO NOT EDIT
#include <rex/ppc.h>

#include <atomic>
#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <mutex>
#include <unordered_map>

namespace {{
// D3D library address ranges; calls between functions inside them aren't recorded.
constexpr uint32_t kCore[][2] = {{{ranges}}};
inline bool InCore(uint32_t a) {{
  for (auto& r : kCore) {{
    if (a >= r[0] && a < r[1]) return true;
  }}
  return false;
}}
const char* g_path = std::getenv("AUTOPORT_D3D_TRACE");
std::mutex g_mutex;
std::unordered_map<uint64_t, uint64_t> g_counts;
std::chrono::steady_clock::time_point g_last_dump = std::chrono::steady_clock::now();

void Dump() {{
  FILE* f = std::fopen(g_path, "w");
  if (!f) return;
  for (auto& [key, n] : g_counts) {{
    std::fprintf(f, "%08X %08X %llu\\n", uint32_t(key >> 32), uint32_t(key), (unsigned long long)n);
  }}
  std::fclose(f);
}}

inline void Record(uint32_t func, uint32_t lr) {{
  if (!g_path || (InCore(lr) && InCore(func))) return;
  std::lock_guard<std::mutex> lock(g_mutex);
  ++g_counts[(uint64_t(func) << 32) | lr];
  auto now = std::chrono::steady_clock::now();
  if (now - g_last_dump > std::chrono::seconds(2)) {{
    g_last_dump = now;
    Dump();
  }}
}}
}}  // namespace

"""

FUNC = """extern "C" void __imp__sub_{a:08X}(PPCContext& __restrict, uint8_t*);
extern "C" void sub_{a:08X}(PPCContext& __restrict ctx, uint8_t* base) {{
  Record(0x{a:08X}, uint32_t(ctx.lr));
  __imp__sub_{a:08X}(ctx, base);
}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest", type=Path)
    ap.add_argument("triage_json", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--range", action="append", default=[],
                    help="extra D3D library address range LO-HI (hex) to trace, for libraries "
                         "linked in more than one block; may be repeated")
    ap.add_argument("--extra", default="",
                    help="comma-separated extra function addresses to trace (e.g. LTCG-inlined draw paths "
                         "outside the core); calls to these are recorded from any caller")
    args = ap.parse_args()
    manifest = args.manifest.resolve()
    gen = manifest.parent / tomllib.loads(manifest.read_text())["entrypoint"]["out_directory_path"]
    lo, hi = (int(x, 16) for x in json.loads(args.triage_json.read_text())["d3d_core"])
    ranges = [(lo, hi)] + [tuple(int(x, 16) for x in r.split("-")) for r in args.range]
    funcs = set()
    for cpp in gen.glob("*_recomp.*.cpp"):
        for m in re.finditer(r"^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)", cpp.read_text(errors="replace"), re.M):
            a = int(m.group(1), 16)
            if any(r_lo <= a < r_hi for r_lo, r_hi in ranges):
                funcs.add(a)
    extra = {int(x, 16) for x in args.extra.split(",") if x}
    funcs |= extra
    ranges_text = ", ".join(f"{{0x{r_lo:08X}, 0x{r_hi:08X}}}" for r_lo, r_hi in ranges)
    out = HEADER.format(ranges=ranges_text) + "\n".join(FUNC.format(a=a) for a in sorted(funcs))
    args.out.write_text(out)
    print(f"{len(funcs)} D3D core functions traced -> {args.out}")


if __name__ == "__main__":
    main()
