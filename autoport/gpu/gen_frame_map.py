#!/usr/bin/env python3
"""Generate a broad frame-map tracer for a recompiled title (logging only).

Hooks every function reachable from the given render roots (up to --depth
calls deep) plus every D3D-library function the engine calls directly, and
writes a C++ file whose hooks log begin/end with arguments and a guest call
chain for a couple of frames when triggered (see the generated header).

Usage: gen_frame_map.py <generated dir> <out.cpp> --root 8244C540 [--root ...]
         [--depth 6] [--core-lo 826C0000 --core-hi 826E0000] [--exclude-file f]
         [--present 821F13A8]
"""
import argparse
import re
from collections import deque
from pathlib import Path

FUNC_RE = re.compile(r"^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)")
CALL_RE = re.compile(r"//\s+bl\s+0x([0-9a-f]{8})")


def parse(generated: Path):
    callees = {}
    for cpp in sorted(generated.glob("*.cpp")):
        current = None
        for line in cpp.read_text(errors="replace").splitlines():
            m = FUNC_RE.match(line)
            if m:
                current = int(m.group(1), 16)
                callees[current] = []
                continue
            if current is not None:
                c = CALL_RE.search(line)
                if c:
                    callees[current].append(int(c.group(1), 16))
    return callees


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("generated", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--root", action="append", required=True)
    ap.add_argument("--depth", type=int, default=6)
    ap.add_argument("--core-lo", default="826C0000")
    ap.add_argument("--core-hi", default="826E0000")
    ap.add_argument("--runtime-lo", default="827E0000", help="compiler/runtime helpers from here up are skipped")
    ap.add_argument("--exclude-file", type=Path)
    ap.add_argument("--present", default="821F13A8")
    ap.add_argument("--up-root", action="append", default=[],
                    help="also hook callers of this function, --up levels up (and their subtrees to --depth)")
    ap.add_argument("--up", type=int, default=6)
    args = ap.parse_args()

    callees = parse(args.generated)
    core_lo, core_hi = int(args.core_lo, 16), int(args.core_hi, 16)
    runtime_lo = int(args.runtime_lo, 16)
    present = int(args.present, 16)
    exclude = set()
    if args.exclude_file and args.exclude_file.exists():
        exclude = {int(x, 16) for x in args.exclude_file.read_text().split()}
    exclude.add(present)

    def hookable(f):
        return f in callees and f < runtime_lo and f not in exclude

    # Callers of the --up-root functions, --up levels up, become extra roots.
    callers_of = {}
    for f, cs in callees.items():
        for c in cs:
            callers_of.setdefault(c, set()).add(f)
    extra_roots = set()
    frontier = {int(r, 16) for r in args.up_root}
    extra_roots |= frontier
    for _ in range(args.up):
        frontier = {c for f in frontier for c in callers_of.get(f, ()) if hookable(c)} - extra_roots
        extra_roots |= frontier
    # Engine subtree under the roots (stop descending into the D3D core).
    depth_of = {}
    queue = deque()
    for r in list(args.root) + [f"{x:08X}" for x in sorted(extra_roots)]:
        r = int(r, 16)
        depth_of[r] = 0
        queue.append(r)
    while queue:
        f = queue.popleft()
        if depth_of[f] >= args.depth or core_lo <= f < core_hi:
            continue
        for c in callees.get(f, []):
            if c not in depth_of and hookable(c):
                depth_of[c] = depth_of[f] + 1
                queue.append(c)
    # D3D entry points: core functions called from engine code anywhere.
    core_entries = set()
    for f, cs in callees.items():
        if core_lo <= f < core_hi:
            continue
        for c in cs:
            if core_lo <= c < core_hi and hookable(c):
                core_entries.add(c)
    hooks = sorted(set(depth_of) | core_entries)
    hooks = [f for f in hooks if hookable(f)]

    out = []
    out.append("// Auto-generated by autoport/gpu/gen_frame_map.py - DO NOT EDIT")
    out.append("//")
    out.append("// AUTOPORT_FRAME_MAP=<file>: when <file>.trigger appears, logs every call to")
    out.append(f"// {len(hooks)} hooked functions (engine render subtree of {', '.join(args.root)} to")
    out.append(f"// depth {args.depth} + {len(core_entries)} D3D entry points) for the next")
    out.append("// AUTOPORT_FRAME_MAP_FRAMES (default 2) frames, between Presents, with the")
    out.append("// first arguments and the guest caller. Per-function lines are capped per")
    out.append("// frame (AUTOPORT_FRAME_MAP_CAP, default 64); call counts are summarized at")
    out.append("// each frame end. Logging only.")
    out.append("#include <rex/ppc.h>")
    out.append("")
    out.append("#include <cstdio>")
    out.append("#include <cstdlib>")
    out.append("#include <filesystem>")
    out.append("#include <mutex>")
    out.append("#include <string>")
    out.append("#include <thread>")
    out.append("#include <unordered_map>")
    out.append("")
    out.append("namespace {")
    out.append("")
    out.append("std::mutex g_mutex;")
    out.append("FILE* g_out = nullptr;")
    out.append("volatile int g_frames_left = 0;")
    out.append("unsigned g_sequence = 0;")
    out.append("std::unordered_map<uint32_t, unsigned> g_counts;")
    out.append("thread_local int t_depth = 0;")
    out.append("")
    out.append("const char* Path() {")
    out.append('  static const char* path = std::getenv("AUTOPORT_FRAME_MAP");')
    out.append("  return path;")
    out.append("}")
    out.append("unsigned Cap() {")
    out.append('  static const unsigned cap = std::getenv("AUTOPORT_FRAME_MAP_CAP") ? unsigned(std::atoi(std::getenv("AUTOPORT_FRAME_MAP_CAP"))) : 64u;')
    out.append("  return cap;")
    out.append("}")
    out.append("")
    out.append("inline bool Active() { return g_frames_left > 0; }")
    out.append("")
    out.append("void Begin(uint32_t func, PPCContext& ctx) {")
    out.append("  std::lock_guard<std::mutex> lock(g_mutex);")
    out.append("  if (!g_out) return;")
    out.append("  unsigned& n = g_counts[func];")
    out.append("  if (n++ < Cap()) {")
    out.append('    std::fprintf(g_out, "%7u t%-6zu %*s> %08X lr %08X r3 %08X r4 %08X r5 %08X r6 %08X r7 %08X\\n", g_sequence++,')
    out.append("                 std::hash<std::thread::id>()(std::this_thread::get_id()) % 1000000, t_depth * 2, \"\", func,")
    out.append("                 uint32_t(ctx.lr), ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, ctx.r7.u32);")
    out.append("  }")
    out.append("}")
    out.append("void End(uint32_t func, PPCContext& ctx) {")
    out.append("  std::lock_guard<std::mutex> lock(g_mutex);")
    out.append("  if (!g_out) return;")
    out.append("  if (g_counts[func] <= Cap()) {")
    out.append('    std::fprintf(g_out, "%7u %*s< %08X -> r3 %08X\\n", g_sequence++, t_depth * 2 + 8, "", func, ctx.r3.u32);')
    out.append("  }")
    out.append("}")
    out.append("")
    out.append("void DumpCounts() {")
    out.append('  std::fprintf(g_out, "------ call counts this frame\\n");')
    out.append("  for (auto& [func, n] : g_counts) {")
    out.append('    if (n) std::fprintf(g_out, "count %08X %u\\n", func, n);')
    out.append("  }")
    out.append("  g_counts.clear();")
    out.append("}")
    out.append("")
    out.append("}  // namespace")
    out.append("")
    out.append('extern "C" void autoport_frame_map_present() {')
    out.append("  if (!Path()) return;")
    out.append("  std::lock_guard<std::mutex> lock(g_mutex);")
    out.append("  if (g_frames_left > 0) {")
    out.append("    DumpCounts();")
    out.append('    std::fprintf(g_out, "------ present (frame end)\\n");')
    out.append("    std::fflush(g_out);")
    out.append("    if (--g_frames_left == 0) {")
    out.append("      std::fclose(g_out);")
    out.append("      g_out = nullptr;")
    out.append("    }")
    out.append("    return;")
    out.append("  }")
    out.append('  const std::string trigger = std::string(Path()) + ".trigger";')
    out.append("  if (std::filesystem::exists(trigger)) {")
    out.append("    std::error_code ec;")
    out.append("    std::filesystem::remove(trigger, ec);")
    out.append('    g_out = std::fopen(Path(), "w");')
    out.append("    if (g_out) {")
    out.append('      const char* frames = std::getenv("AUTOPORT_FRAME_MAP_FRAMES");')
    out.append("      g_frames_left = frames ? std::atoi(frames) : 2;")
    out.append("      g_sequence = 0;")
    out.append("      g_counts.clear();")
    out.append("    }")
    out.append("  }")
    out.append("}")
    out.append("")
    out.append("#define AUTOPORT_FRAME_MAP_HOOK(addr)                                            \\")
    out.append('  extern "C" void __imp__sub_##addr(PPCContext& __restrict, uint8_t*);             \\')
    out.append('  extern "C" void sub_##addr(PPCContext& __restrict ctx, uint8_t* base) {          \\')
    out.append("    if (!Active()) {                                                               \\")
    out.append("      __imp__sub_##addr(ctx, base);                                                \\")
    out.append("      return;                                                                      \\")
    out.append("    }                                                                              \\")
    out.append("    Begin(0x##addr, ctx);                                                          \\")
    out.append("    ++t_depth;                                                                     \\")
    out.append("    __imp__sub_##addr(ctx, base);                                                  \\")
    out.append("    --t_depth;                                                                     \\")
    out.append("    End(0x##addr, ctx);                                                            \\")
    out.append("  }")
    out.append("")
    for f in hooks:
        tag = "d3d" if core_lo <= f < core_hi else f"depth {depth_of.get(f, '-')}"
        out.append(f"AUTOPORT_FRAME_MAP_HOOK({f:08X})  // {tag}")
    out.append("")
    args.out.write_text("\n".join(out))
    print(f"{len(hooks)} hooks ({len(core_entries)} D3D entries, {len(depth_of)} engine subtree)")


if __name__ == "__main__":
    main()
